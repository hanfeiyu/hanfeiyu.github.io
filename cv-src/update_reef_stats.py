"""Refresh the CV's dated REEF star-count snapshot without third-party packages."""

import argparse
from datetime import date, datetime
import json
from pathlib import Path
import re
import sys
import tempfile
from urllib.error import URLError
from urllib.request import Request, urlopen
from zoneinfo import ZoneInfo


REPOSITORY = "Human-Agent-Society/reef"
SNAPSHOT = Path(__file__).with_name("reef-stats.tex")


def fetch_count():
    request = Request(
        f"https://api.github.com/repos/{REPOSITORY}",
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "hanfeiyu-cv-build",
        },
    )
    with urlopen(request, timeout=10) as response:
        data = json.load(response)
    if not isinstance(data, dict) or data.get("full_name") != REPOSITORY:
        raise ValueError("unexpected repository metadata")
    count = data.get("stargazers_count")
    if type(count) is not int or count < 0:
        raise ValueError("invalid GitHub star count")
    return count


def format_count(count):
    if count < 1000:
        return str(count)
    return f"{count / 1000:.1f}".rstrip("0").rstrip(".") + "K"


def render_snapshot(count, checked_on):
    return (
        "% Generated by update_reef_stats.py from GitHub's public API.\n"
        rf"\newcommand{{\ReefGitHubStars}}{{{count:,}}}" + "\n"
        rf"\newcommand{{\ReefGitHubStarsCompact}}{{{format_count(count)}}}" + "\n"
        rf"\newcommand{{\ReefGitHubStarsAsOf}}{{{checked_on.isoformat()}}}" + "\n"
    )


def cached_summary(path):
    text = path.read_text(encoding="utf-8")
    count = re.search(r"\\newcommand\{\\ReefGitHubStars\}\{([0-9,]+)\}", text)
    checked_on = re.search(r"\\newcommand\{\\ReefGitHubStarsAsOf\}\{([0-9-]+)\}", text)
    if not count or not checked_on:
        raise ValueError("missing or invalid saved star-count snapshot")
    parsed_count = int(count[1].replace(",", ""))
    parsed_date = date.fromisoformat(checked_on[1])
    if text != render_snapshot(parsed_count, parsed_date):
        raise ValueError("invalid saved star-count snapshot")
    return f"{parsed_count:,} stars as of {parsed_date.isoformat()}"


def refresh_snapshot(path=SNAPSHOT, offline=False):
    if offline:
        print(f"REEF: using saved snapshot ({cached_summary(path)}).")
        return
    try:
        count = fetch_count()
        checked_on = datetime.now(ZoneInfo("America/Los_Angeles")).date()
        text = render_snapshot(count, checked_on)
    except (URLError, OSError, ValueError) as error:
        # Retain the original date, never label stale data as today's count.
        print(
            f"Warning: REEF refresh unavailable ({error}); "
            f"using saved snapshot ({cached_summary(path)}).",
            file=sys.stderr,
        )
        return
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=path.parent, delete=False,
            prefix=".reef-stats-", suffix=".tmp",
        ) as temporary:
            temporary.write(text)
            temporary_path = Path(temporary.name)
        try:
            temporary_path.replace(path)
        finally:
            temporary_path.unlink(missing_ok=True)
    print(f"REEF: refreshed {count:,} stars as of {checked_on.isoformat()}.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true", help="keep the saved count and date")
    arguments = parser.parse_args()
    refresh_snapshot(offline=arguments.offline)
